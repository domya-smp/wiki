def render(drink):
    # Normalize: optional glint flag as trailing True
    glint = False
    d = list(drink)
    if len(d) > 11 and d[-1] is True:
        glint = True
        d = d[:-1]
    slug, name, desc, ingredients, cook, barrel, age, color, diff, alc, effects = d

    # Барьер/выдержка строки
    barrel_line = f"**Бочка:** {barrel}" if barrel else "**Бочка:** не нужна"
    age_line = f"**Выдержка:** {age} игровых лет" if age else "**Выдержка:** не требуется"
    glint_line = "**Сияние:** да (зачарованное)" if glint else None

    # Ingredient table
    ing_rows = "\n".join(f"| {n} | {q} |" for n, q in ingredients)
    # Effects table
    eff_rows = "\n".join(f"| {e} | {lvl} | {dur} |" for e, lvl, dur in effects)

    md = f"""# {name}

*{desc}*

!!! info "Краткая справка"
    **Сложность:** {diff} · **Опьянение:** {alc} · {barrel_line}

## Ингредиенты

| Предмет | Количество |
|---|---|
{ing_rows}

## Параметры

- **Цвет:** {color}
- **Время варки:** {cook} мин
- {age_line}
"""
    if glint_line:
        md += f"- {glint_line}\n"

    md += f"""
## Эффекты

| Эффект | Уровень | Длительность |
|---|---|---|
{eff_rows}

*Диапазон длительности зависит от качества напитка: меньшее значение при худшем, большее — при идеальном.*
"""
    return md


def main():
    # Сформируем nav
    nav_drinks = [{"Обзор": "drinks/index.md"}]
    category_index_entries = []
    for cat_slug, cat_name, cat_desc in CATEGORIES:
        cat_dir = DOCS / cat_slug
        cat_dir.mkdir(parents=True, exist_ok=True)
        drinks = DRINKS.get(cat_slug, [])
        # Category index
        cat_index = f"# {cat_name}\n\n{cat_desc}\n\n## Рецепты\n\n"
        cat_nav = [{"Обзор": f"drinks/{cat_slug}/index.md"}]
        for drink in drinks:
            slug = drink[0]
            name = drink[1]
            (cat_dir / f"{slug}.md").write_text(render(drink), encoding="utf-8")
            cat_index += f"- [{name}]({slug}.md)\n"
            cat_nav.append({name: f"drinks/{cat_slug}/{slug}.md"})
        (cat_dir / "index.md").write_text(cat_index, encoding="utf-8")
        nav_drinks.append({cat_name: cat_nav})
        category_index_entries.append(f"- **[{cat_name}]({cat_slug}/index.md)** — {cat_desc}")

    # Главная страница раздела напитков
    top_index = f"""# Напитки

Система приготовления напитков на базе плагина **BreweryX**. Варка идёт в котле, некоторые напитки требуют настоя в бочке.

## Категории

{chr(10).join(category_index_entries)}

## Как читать рецепт

Сложность (от 1 до 10) показывает, насколько точно нужно соблюдать рецепт. Чем выше — тем сильнее эффекты при идеальном качестве. Длительность эффектов указана диапазоном: меньшее значение получится при худшем качестве, большее — при идеальном.
"""
    DOCS.mkdir(parents=True, exist_ok=True)
    (DOCS / "index.md").write_text(top_index, encoding="utf-8")

    # Обновим mkdocs.yml nav
    cfg_path = ROOT / "mkdocs.yml"
    cfg = yaml.safe_load(cfg_path.read_text(encoding="utf-8"))
    cfg["nav"] = [
        {"Главная": "index.md"},
        {"Напитки": nav_drinks},
    ]
    cfg_path.write_text(
        yaml.safe_dump(cfg, allow_unicode=True, sort_keys=False),
        encoding="utf-8",
    )
    print("Сгенерировано", sum(len(v) for v in DRINKS.values()), "страниц.")


if __name__ == "__main__":
    main()
